/**
 * 选文件夹（`system.folder-pick@1`）。
 *
 * 它做的事只有一件：弹出系统原生的选文件夹面板，把**用户亲手挑的那一个**目录的
 * 绝对路径交给插件。
 *
 * 边界说清楚，免得被当成文件访问：
 * - 只回一个路径字符串。Host 不读目录内容，也不因此给插件任何文件读写能力。
 * - 面板由用户操作，取消就返回 `undefined`——插件拿不到「用户没选的东西」。
 * - 只有用户当前正在查看的插件界面能调用。后台插件弹不出面板，
 *   所以用户永远知道这个面板是谁弹的。
 * - grantGated：只有官方 seed 名单里的插件拿得到这条能力。
 */
export interface FolderPickClient {
  /**
   * 弹出系统选文件夹面板。
   *
   * @returns 用户选中目录的绝对路径；用户取消时是 `undefined`。
   */
  pick(): Promise<string | undefined>;
}
